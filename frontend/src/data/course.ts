const SOURCES = new Map<string, LessonSource>([...LESSONS_A, ...LESSONS_B, ...LESSONS_C, ...LESSONS_D, ...LESSONS_E, ...LESSONS_F].map((l) => [l.id, l]));

/** Все уроки курса в порядке прохождения: номер, этап, уровень и предыдущий урок вычисляются из STRUCTURE. */
export const LESSONS: Lesson[] = STRUCTURE.flatMap((st, si) => st.lessons.map((id) => ({ id, st, si }))).map(({ id, st, si }, i, all) => {
  const src = SOURCES.get(id);
  if (!src) throw new Error(`Урок ${id} указан в структуре курса, но не найден`);
  const extra = EXTRAS[id];
  return {
    ...src,
    order: i + 1,
    block: st.title,
    stageNo: si + 1,
    level: st.level,
    practice: src.practice ?? extra?.practice ?? [],
    outcome: src.outcome ?? extra?.outcome ?? '',
    prerequisites: i === 0 ? [] : [all[i - 1].id],
    durationMin: src.stages.reduce((a, s) => a + s.minutes, 0),
  };
});

/** Этапы курса с их уроками. */
export const COURSE_STAGES = STRUCTURE.map((st, i) => ({
  no: i + 1,
  name: st.title,
  level: st.level,
  goal: st.goal,
  lessons: LESSONS.filter((l) => l.stageNo === i + 1),
}));
export type CourseStage = (typeof COURSE_STAGES)[number];

/** Исторический алиас: блоки = этапы. */
export const COURSE_BLOCKS = COURSE_STAGES;

